--------------------------------------------------------------------------------
-- TABELA: Tutor
--------------------------------------------------------------------------------
CREATE TABLE Tutor (
    id_tutor    NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nome        NVARCHAR2(100)  NOT NULL,
    telefone    NVARCHAR2(20),
    email       NVARCHAR2(100),
    CONSTRAINT PK_Tutor PRIMARY KEY (id_tutor)
);

COMMENT ON TABLE Tutor IS 'Tutor (responsavel) do pet cadastrado na clinica';
COMMENT ON COLUMN Tutor.id_tutor IS 'Identificador unico do tutor';
COMMENT ON COLUMN Tutor.nome IS 'Nome completo do tutor';
COMMENT ON COLUMN Tutor.telefone IS 'Telefone de contato do tutor';
COMMENT ON COLUMN Tutor.email IS 'E-mail de contato do tutor';

--------------------------------------------------------------------------------
-- TABELA: Clinica
--------------------------------------------------------------------------------
CREATE TABLE Clinica (
    id_clinica  NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nome        NVARCHAR2(100)  NOT NULL,
    endereco    NVARCHAR2(200)  NOT NULL,
    telefone    NVARCHAR2(20),
    CONSTRAINT PK_Clinica PRIMARY KEY (id_clinica)
);

COMMENT ON TABLE Clinica IS 'Clinica veterinaria parceira da Clyvo Vet';
COMMENT ON COLUMN Clinica.id_clinica IS 'Identificador unico da clinica';
COMMENT ON COLUMN Clinica.nome IS 'Nome fantasia da clinica';
COMMENT ON COLUMN Clinica.endereco IS 'Endereco completo da clinica';
COMMENT ON COLUMN Clinica.telefone IS 'Telefone de contato da clinica';

--------------------------------------------------------------------------------
-- TABELA: Vacina
--------------------------------------------------------------------------------
CREATE TABLE Vacina (
    id_vacina   NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nome        NVARCHAR2(100)  NOT NULL,
    descricao   NVARCHAR2(200),
    CONSTRAINT PK_Vacina PRIMARY KEY (id_vacina)
);

COMMENT ON TABLE Vacina IS 'Catalogo de vacinas disponiveis para aplicacao nos pets';
COMMENT ON COLUMN Vacina.id_vacina IS 'Identificador unico da vacina';
COMMENT ON COLUMN Vacina.nome IS 'Nome da vacina';
COMMENT ON COLUMN Vacina.descricao IS 'Descricao/observacoes sobre a vacina';

--------------------------------------------------------------------------------
-- TABELA: Pet
--------------------------------------------------------------------------------
CREATE TABLE Pet (
    id_pet      NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nome        NVARCHAR2(100)  NOT NULL,
    idade       NUMBER(10),
    especie     NVARCHAR2(50)   NOT NULL,
    raca        NVARCHAR2(50),
    id_tutor    NUMBER(10)      NOT NULL,
    CONSTRAINT PK_Pet PRIMARY KEY (id_pet),
    CONSTRAINT FK_Pet_Tutor FOREIGN KEY (id_tutor)
        REFERENCES Tutor (id_tutor) ON DELETE CASCADE
);

COMMENT ON TABLE Pet IS 'Pet cadastrado, vinculado a um tutor';
COMMENT ON COLUMN Pet.id_pet IS 'Identificador unico do pet';
COMMENT ON COLUMN Pet.nome IS 'Nome do pet';
COMMENT ON COLUMN Pet.idade IS 'Idade do pet, em anos';
COMMENT ON COLUMN Pet.especie IS 'Especie do pet (ex: Cachorro, Gato)';
COMMENT ON COLUMN Pet.raca IS 'Raca do pet';
COMMENT ON COLUMN Pet.id_tutor IS 'Chave estrangeira para o tutor responsavel (Tutor.id_tutor)';

CREATE INDEX IX_Pet_id_tutor ON Pet (id_tutor);

--------------------------------------------------------------------------------
-- TABELA: Aplicacao_vacina
--------------------------------------------------------------------------------
CREATE TABLE Aplicacao_vacina (
    id_aplicacao    NUMBER(10)  GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    data_aplicacao  TIMESTAMP   NOT NULL,
    id_vacina       NUMBER(10)  NOT NULL,
    id_pet          NUMBER(10)  NOT NULL,
    CONSTRAINT PK_Aplicacao_vacina PRIMARY KEY (id_aplicacao),
    CONSTRAINT FK_AplicacaoVacina_Pet FOREIGN KEY (id_pet)
        REFERENCES Pet (id_pet) ON DELETE CASCADE,
    CONSTRAINT FK_AplicacaoVacina_Vacina FOREIGN KEY (id_vacina)
        REFERENCES Vacina (id_vacina) ON DELETE CASCADE
);

COMMENT ON TABLE Aplicacao_vacina IS 'Registro de aplicacao de uma vacina em um pet';
COMMENT ON COLUMN Aplicacao_vacina.id_aplicacao IS 'Identificador unico do registro de aplicacao';
COMMENT ON COLUMN Aplicacao_vacina.data_aplicacao IS 'Data/hora em que a vacina foi aplicada';
COMMENT ON COLUMN Aplicacao_vacina.id_vacina IS 'Chave estrangeira para a vacina aplicada (Vacina.id_vacina)';
COMMENT ON COLUMN Aplicacao_vacina.id_pet IS 'Chave estrangeira para o pet vacinado (Pet.id_pet)';

CREATE INDEX IX_AplicacaoVacina_id_pet ON Aplicacao_vacina (id_pet);
CREATE INDEX IX_AplicacaoVacina_id_vacina ON Aplicacao_vacina (id_vacina);

--------------------------------------------------------------------------------
-- TABELA: Consulta (associativa Pet <-> Clinica)
--------------------------------------------------------------------------------
CREATE TABLE Consulta (
    id_consulta     NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    data_consulta   TIMESTAMP       NOT NULL,
    descricao       NVARCHAR2(200),
    id_pet          NUMBER(10)      NOT NULL,
    id_clinica      NUMBER(10)      NOT NULL,
    CONSTRAINT PK_Consulta PRIMARY KEY (id_consulta),
    CONSTRAINT FK_Consulta_Pet FOREIGN KEY (id_pet)
        REFERENCES Pet (id_pet) ON DELETE CASCADE,
    CONSTRAINT FK_Consulta_Clinica FOREIGN KEY (id_clinica)
        REFERENCES Clinica (id_clinica) ON DELETE CASCADE
);

COMMENT ON TABLE Consulta IS 'Consulta veterinaria de um pet em uma clinica';
COMMENT ON COLUMN Consulta.id_consulta IS 'Identificador unico da consulta';
COMMENT ON COLUMN Consulta.data_consulta IS 'Data/hora da consulta';
COMMENT ON COLUMN Consulta.descricao IS 'Descricao/observacoes da consulta';
COMMENT ON COLUMN Consulta.id_pet IS 'Chave estrangeira para o pet atendido (Pet.id_pet)';
COMMENT ON COLUMN Consulta.id_clinica IS 'Chave estrangeira para a clinica onde ocorreu (Clinica.id_clinica)';

CREATE INDEX IX_Consulta_id_pet ON Consulta (id_pet);
CREATE INDEX IX_Consulta_id_clinica ON Consulta (id_clinica);

--------------------------------------------------------------------------------
-- TABELA: Historico_saude
--------------------------------------------------------------------------------
CREATE TABLE Historico_saude (
    id_historico    NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    descricao       NVARCHAR2(255)  NOT NULL,
    data_registro   TIMESTAMP       NOT NULL,
    id_pet          NUMBER(10)      NOT NULL,
    CONSTRAINT PK_Historico_saude PRIMARY KEY (id_historico),
    CONSTRAINT FK_HistoricoSaude_Pet FOREIGN KEY (id_pet)
        REFERENCES Pet (id_pet) ON DELETE CASCADE
);

COMMENT ON TABLE Historico_saude IS 'Historico de saude/eventos clinicos de um pet';
COMMENT ON COLUMN Historico_saude.id_historico IS 'Identificador unico do registro de historico';
COMMENT ON COLUMN Historico_saude.descricao IS 'Descricao do evento/registro de saude';
COMMENT ON COLUMN Historico_saude.data_registro IS 'Data/hora em que o registro foi feito';
COMMENT ON COLUMN Historico_saude.id_pet IS 'Chave estrangeira para o pet (Pet.id_pet)';

